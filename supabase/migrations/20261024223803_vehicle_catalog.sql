-- Vehicle catalog: makes + models as reference data (needed in every environment, so it's a migration,
-- not seed). Read-only through the API. Add new models with a new migration.

create table public.vehicle_makes (
  id smallint generated always as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$')
);

create table public.vehicle_models (
  id integer generated always as identity primary key,
  make_id smallint not null references public.vehicle_makes (id) on delete restrict,
  name text not null check (char_length(name) between 1 and 60),
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  unique (make_id, slug),
  -- Target for the composite FK on vehicles (make_id, model_id): a model must belong to its make.
  unique (make_id, id)
);

alter table public.vehicle_makes enable row level security;
alter table public.vehicle_models enable row level security;

revoke all on public.vehicle_makes, public.vehicle_models from anon, authenticated;
grant select on public.vehicle_makes, public.vehicle_models to anon, authenticated;

create policy "Anyone can read makes" on public.vehicle_makes for select to anon, authenticated using (true);
create policy "Anyone can read models" on public.vehicle_models for select to anon, authenticated using (true);
-- No insert/update/delete policies: catalog changes only through migrations.

